import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

export interface BankEntry {
  name: string;
  url: string | string[];
  bus?: string;
  loop?: boolean;
}

export interface BankManifest {
  /** Optional default bus that all entries fall back to. */
  defaultBus?: string;
  /** Sound entries — keyed by name or as an array. */
  sounds: BankEntry[] | Record<string, Omit<BankEntry, 'name'>>;
}

/**
 * Read a sound manifest JSON and emit a typed module:
 *
 *   - the union of every sound name (`SoundName`)
 *   - `BANK`, the entries as data
 *   - a `loadBank(engine, options)` function that loads every entry through
 *     `engine.preload`, so it gets the preload concurrency cap and progress
 *
 * Drop the generated file into your repo and `engine.sound("coin")` will be
 * autocompleted as a literal type.
 */
export async function runGen(argv: string[]): Promise<void> {
  const args = parseArgs(argv);
  const raw = await readFile(args.input, 'utf-8');
  const manifest: BankManifest = JSON.parse(raw);
  const out = renderBank(manifest);
  await writeFile(args.out, out, 'utf-8');
  process.stdout.write(`Wrote ${args.out} (${normalizeBank(manifest).length} entries).\n`);
}

interface ParsedArgs {
  input: string;
  out: string;
}

function parseArgs(argv: string[]): ParsedArgs {
  const out: ParsedArgs = { input: '', out: 'bank.gen.ts' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]!;
    if (a === '--out') out.out = argv[++i] ?? out.out;
    else out.input = a;
  }
  if (!out.input) {
    process.stderr.write('Usage: zvuk gen <bank.json> [--out bank.gen.ts]\n');
    process.exit(1);
  }
  out.input = resolve(out.input);
  out.out = resolve(out.out);
  return out;
}

export function normalizeBank(manifest: BankManifest): BankEntry[] {
  if (!manifest || typeof manifest !== 'object' || manifest.sounds == null) {
    throw new Error('Bank manifest needs a "sounds" array or object.');
  }
  const entries = Array.isArray(manifest.sounds)
    ? manifest.sounds
    : Object.entries(manifest.sounds).map(([name, entry]) => ({ name, ...entry }));
  const seen = new Set<string>();
  for (const e of entries) {
    if (!e.name || !e.url) throw new Error(`Bank entry ${JSON.stringify(e)} needs a "name" and a "url".`);
    if (seen.has(e.name)) throw new Error(`Bank entry "${e.name}" is listed twice.`);
    seen.add(e.name);
  }
  return entries;
}

/**
 * The generated module's source. Pure, so it can be tested without files.
 *
 * `loop` is kept on each entry as data: it describes how the sound is meant
 * to play, which `loadSound` has no option for. v1 put it inside the load
 * options, where it was silently ignored.
 */
export function renderBank(manifest: BankManifest): string {
  const entries = normalizeBank(manifest);
  const defaultBus = manifest.defaultBus;
  const lines: string[] = [];
  lines.push('// AUTOGENERATED by `zvuk gen`. Do not edit.');
  lines.push("import type { Engine, PreloadOptions } from '@schmooky/zvuk';");
  lines.push('');
  if (entries.length === 0) {
    lines.push('export type SoundName = never;');
  } else {
    lines.push('export type SoundName =');
    entries.forEach((e, i) => {
      lines.push(`  | ${JSON.stringify(e.name)}${i === entries.length - 1 ? ';' : ''}`);
    });
  }
  lines.push('');
  lines.push('export const BANK = [');
  for (const e of entries) {
    const fields = [`name: ${JSON.stringify(e.name)}`, `url: ${JSON.stringify(e.url)}`];
    const bus = e.bus ?? defaultBus;
    if (bus) fields.push(`bus: ${JSON.stringify(bus)}`);
    if (e.loop) fields.push('loop: true');
    lines.push(`  { ${fields.join(', ')} },`);
  }
  lines.push('] as const;');
  lines.push('');
  lines.push('/** Load every sound in the bank. Rejects with PreloadError if any fail. */');
  lines.push('export function loadBank(engine: Engine, options: PreloadOptions = {}): Promise<void> {');
  lines.push('  return engine.preload(');
  lines.push('    BANK.map((entry) => ({');
  lines.push('      name: entry.name,');
  lines.push('      url: entry.url,');
  lines.push("      options: 'bus' in entry ? { bus: entry.bus as string } : {},");
  lines.push('    })),');
  lines.push('    options,');
  lines.push('  );');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}
